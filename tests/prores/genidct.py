# Generates the unrolled integer IDCT methods (ffmpeg's simple IDCT
# variants) for prores/ and dnxhd/: the 64 intermediate values live in
# local variables rather than a list.
#
# Author: Alexius Academia
# Date: 2026-10-25

import sys

def gen(name, W, row_shift, dc, bias, col_round, col_shift, lo, hi, prefix, wrap=True):
    """dc: 'shift:<k>' (DC-only row = x0 << k), 'round1' ((x0+1)>>1),
    or 'full' (no shortcut: the full formula, as ffmpeg's NEON code)."""
    W1, W2, W3, W4, W5, W6, W7 = W
    rr = 1 << (row_shift - 1)
    L = []
    o = L.append
    o(f"    // Generated by tests/prores/genidct.py (ffmpeg's simple IDCT: rows")
    o(f"    // shift {row_shift}, columns {col_shift}, output clipped to {lo}…{hi}).")
    o(f"    fn {name}(_ b: Int, _ m: Int, _ off: Int, _ stride: Int) {{")
    o(f"        let s = b << 6")
    for r in range(8):
        for c in range(8):
            o(f"        var r{r}c{c} = 0")
    def w16(e):
        return f"((({e}) + 32768) & 65535) - 32768" if wrap else e
    for r in range(8):
        bs = f" + {bias}" if (r == 0 and bias) else ""
        if r == 0:
            o(f"        if true {{")
        else:
            o(f"        if (m & {1 << r}) != 0 {{")
        base = f"s + {r * 8}" if r else "s"
        for k in range(8):
            o(f"            let x{k} = blk[{base}{' + ' + str(k) if k else ''}]")
        for k in range(8):
            o(f"            blk[{base}{' + ' + str(k) if k else ''}] = 0")
        o(f"            if (x1 | x2 | x3 | x4 | x5 | x6 | x7) == 0 {{")
        if dc.startswith('shift:'):
            k = int(dc[6:])
            o(f"                let v = {w16(f'x0 << {k}')}{bs}")
        elif dc == 'round1':
            o(f"                let v = {w16('(x0 + 1) >> 1')}{bs}")
        else:
            o(f"                let v = {w16(f'({W4} * x0 + {rr}) >> {row_shift}')}{bs}")
        for c in range(8):
            o(f"                r{r}c{c} = v")
        o(f"            }} else {{")
        o(f"                var a0 = {W4} * x0 + {rr}")
        o(f"                var a1 = a0")
        o(f"                var a2 = a0")
        o(f"                var a3 = a0")
        o(f"                a0 += {W2} * x2")
        o(f"                a1 += {W6} * x2")
        o(f"                a2 -= {W6} * x2")
        o(f"                a3 -= {W2} * x2")
        o(f"                var b0 = {W1} * x1 + {W3} * x3")
        o(f"                var b1 = {W3} * x1 - {W7} * x3")
        o(f"                var b2 = {W5} * x1 - {W1} * x3")
        o(f"                var b3 = {W7} * x1 - {W5} * x3")
        o(f"                if (x4 | x5 | x6 | x7) != 0 {{")
        o(f"                    a0 += {W4} * x4 + {W6} * x6")
        o(f"                    a1 += -{W4} * x4 - {W2} * x6")
        o(f"                    a2 += -{W4} * x4 + {W2} * x6")
        o(f"                    a3 += {W4} * x4 - {W6} * x6")
        o(f"                    b0 += {W5} * x5 + {W7} * x7")
        o(f"                    b1 += -{W1} * x5 - {W5} * x7")
        o(f"                    b2 += {W7} * x5 + {W3} * x7")
        o(f"                    b3 += {W3} * x5 - {W1} * x7")
        o(f"                }}")
        outs = [("a0 + b0", 0), ("a1 + b1", 1), ("a2 + b2", 2), ("a3 + b3", 3),
                ("a3 - b3", 4), ("a2 - b2", 5), ("a1 - b1", 6), ("a0 - b0", 7)]
        for e, c in outs:
            o(f"                r{r}c{c} = {w16(f'({e}) >> {row_shift}')}{bs}")
        o(f"            }}")
        o(f"        }}")
    # Bias may push row 0 out of int16 range: C stores it in int16.
    if bias and wrap:
        for c in range(8):
            o(f"        r0c{c} = ((r0c{c} + 32768) & 65535) - 32768")
    def clip(e):
        return f"max({lo}, min({hi}, {e}))"
    # Only row 0: every column is flat.
    o(f"        if m == 1 {{")
    for c in range(8):
        o(f"            let v{c} = {clip(f'({W4} * (r0c{c} + {col_round})) >> {col_shift}')}")
    o(f"            var o = off")
    o(f"            for _ in 0..8 {{")
    for c in range(8):
        o(f"                pl[o + {c}] = v{c}" if c else f"                pl[o] = v0")
    o(f"                o += stride")
    o(f"            }}")
    o(f"            return")
    o(f"        }}")
    # Columns.
    o(f"        let hiRows = m > 15")
    for c in range(8):
        o(f"        if true {{")
        o(f"            var a0 = {W4} * (r0c{c} + {col_round})")
        o(f"            var a1 = a0")
        o(f"            var a2 = a0")
        o(f"            var a3 = a0")
        o(f"            a0 += {W2} * r2c{c}")
        o(f"            a1 += {W6} * r2c{c}")
        o(f"            a2 -= {W6} * r2c{c}")
        o(f"            a3 -= {W2} * r2c{c}")
        o(f"            var b0 = {W1} * r1c{c} + {W3} * r3c{c}")
        o(f"            var b1 = {W3} * r1c{c} - {W7} * r3c{c}")
        o(f"            var b2 = {W5} * r1c{c} - {W1} * r3c{c}")
        o(f"            var b3 = {W7} * r1c{c} - {W5} * r3c{c}")
        o(f"            if hiRows {{")
        o(f"                a0 += {W4} * r4c{c} + {W6} * r6c{c}")
        o(f"                a1 += -{W4} * r4c{c} - {W2} * r6c{c}")
        o(f"                a2 += -{W4} * r4c{c} + {W2} * r6c{c}")
        o(f"                a3 += {W4} * r4c{c} - {W6} * r6c{c}")
        o(f"                b0 += {W5} * r5c{c} + {W7} * r7c{c}")
        o(f"                b1 += -{W1} * r5c{c} - {W5} * r7c{c}")
        o(f"                b2 += {W7} * r5c{c} + {W3} * r7c{c}")
        o(f"                b3 += {W3} * r5c{c} - {W1} * r7c{c}")
        o(f"            }}")
        o(f"            let o = off + {c}")
        outs = [("a0 + b0", 0), ("a1 + b1", 1), ("a2 + b2", 2), ("a3 + b3", 3),
                ("a3 - b3", 4), ("a2 - b2", 5), ("a1 - b1", 6), ("a0 - b0", 7)]
        for e, rr_ in outs:
            idx = "o" if rr_ == 0 else ("o + stride" if rr_ == 1 else f"o + {rr_} * stride")
            o(f"            pl[{idx}] = {clip(f'({e}) >> {col_shift}')}")
        o(f"        }}")
    o(f"    }}")
    return "\n".join(L)

if __name__ == "__main__":
    which = sys.argv[1]
    W10 = (22725, 21407, 19265, 16384, 12873, 8867, 4520)
    W12 = (45451, 42813, 38531, 32767, 25746, 17734, 9041)
    W8 = (22725, 21407, 19266, 16383, 12873, 8867, 4520)
    if which == "prores":
        print(gen("idct10", W10, 15, 'round1', 8192, (1 << 17) // 16384, 18, 4, 1019, "pr"))
        print()
        print(gen("idct12", W12, 16, 'round1', 8192, (1 << 16) // 32767, 17, 4, 4091, "pr"))
    elif which == "dnxhd":
        # 8-bit: ffmpeg's NEON simple IDCT (no DC shortcut), clip 0…255.
        print(gen("idct8", W8, 11, 'full', 0, (1 << 19) // 16383, 20, 0, 255, "dx"))
        print()
        print(gen("idct10", W10, 12, 'shift:2', 0, (1 << 18) // 16384, 19, 0, 1023, "dx"))
        print()
        print(gen("idct12", W12, 16, 'round1', 0, (1 << 16) // 32767, 17, 0, 4095, "dx"))
